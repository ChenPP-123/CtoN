def initialize_database(database_url: str | None = None) -> None:
    """Create the current schema. This is an explicit deployment operation."""
    with open_database(database_url) as connection:
        for statement in SCHEMA_STATEMENTS:
            connection.execute(statement)


def require_test_database_url(database_url: str | None = None) -> str:
    """Reject cleanup unless the target database name visibly ends in _test."""
    selected_url = database_url or get_database_url("TEST_DATABASE_URL")
    database_name = unquote(urlparse(selected_url).path).removeprefix("/")
    if not database_name.endswith("_test"):
        raise ValueError("TEST_DATABASE_URL 的数据库名必须以 _test 结尾")
    return selected_url


def reset_test_database(database_url: str | None = None) -> None:
    selected_url = require_test_database_url(database_url)
    with open_database(selected_url) as connection:
        connection.execute(
            """TRUNCATE TABLE
                   operation_leases, daily_update_runs, atmosphere_analyses,
                   air_quality_observations, travel_reports, weather_observations,
                   route_stations, cities, routes
               RESTART IDENTITY CASCADE"""
        )


def initialize_database_from_environment() -> None:
    """Initialize and seed through the non-pooler migration connection."""
    from .seed import seed_database

    migration_url = get_database_url("DATABASE_MIGRATION_URL")
    initialize_database(migration_url)
    with open_database(migration_url) as connection:
        seed_database(connection)


if __name__ == "__main__":
    initialize_database_from_environment()
    print("PostgreSQL schema and fixed route data initialized.")
