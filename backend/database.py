"""PostgreSQL connections and explicit schema initialization."""

from __future__ import annotations

import os
from collections.abc import Iterator
from contextlib import contextmanager
from typing import Any, TypeAlias
from urllib.parse import unquote, urlparse

import psycopg
from psycopg.rows import dict_row


DatabaseRow: TypeAlias = dict[str, Any]
DatabaseConnection: TypeAlias = psycopg.Connection[DatabaseRow]


def get_database_url(variable_name: str = "DATABASE_URL") -> str:
    database_url = os.getenv(variable_name, "").strip()
    if not database_url:
        raise ValueError(f"{variable_name} 尚未配置")
    if urlparse(database_url).scheme not in {"postgresql", "postgres"}:
        raise ValueError(f"{variable_name} 必须是 PostgreSQL 连接地址")
    return database_url


def connect(database_url: str | None = None) -> DatabaseConnection:
    return psycopg.connect(
        database_url or get_database_url(),
        row_factory=dict_row,
        connect_timeout=10,
    )


@contextmanager
def open_database(database_url: str | None = None) -> Iterator[DatabaseConnection]:
    connection = connect(database_url)
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


