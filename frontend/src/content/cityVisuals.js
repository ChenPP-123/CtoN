function seasonFor(date) {
  const month = date ? new Date(`${date}T12:00:00`).getMonth() + 1 : new Date().getMonth() + 1
  if (month >= 3 && month <= 5) return 'spring'
  if (month >= 6 && month <= 8) return 'summer'
  if (month >= 9 && month <= 11) return 'autumn'
  return 'winter'
}

function weatherKinds(text = '') {
  if (/雷|暴/.test(text)) return ['storm', 'rain']
  if (/雨|雪/.test(text) && /雾|霾/.test(text)) return ['rain-fog', 'fog-rain', 'rain']
  if (/雨|雪/.test(text) && /云|阴/.test(text)) return ['rain-cloud', 'rain']
  if (/雨|雪/.test(text)) return ['rain']
  if (/雾|霾/.test(text)) return ['fog']
  if (/云|阴/.test(text)) return ['cloud']
  if (/晴/.test(text)) return ['clear']
  return []
}

function sceneFileFor(visual, season, weatherText) {
  const candidates = weatherKinds(weatherText).map((kind) => `${season}-${kind}.webp`)
  candidates.push(`${season}-normal.webp`)
  return candidates.find((file) => visual.scenes[file]) || Object.keys(visual.scenes)[0]
}

export function visualForCity(cityName, weatherText, date) {
  const visual = cityVisuals[cityName] || cityVisuals.重庆
  const season = seasonFor(date)
  const file = sceneFileFor(visual, season, weatherText)
  const fallbackFile = visual.scenes[`${season}-normal.webp`] ? `${season}-normal.webp` : file
  return {
    ...visual,
    season,
    poem: visual.scenes[file],
    fallbackPoem: visual.scenes[fallbackFile],
    image: `/weather/${visual.slug}/${file}`,
    fallbackImage: `/weather/${visual.slug}/${fallbackFile}`,
    gradient: `linear-gradient(135deg, ${visual.primary}, #172c32 82%)`,
  }
}
